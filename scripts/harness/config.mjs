/** PATH that finds cargo even in terminals hosted by packaged (MSIX) apps; see dev.ps1. */
export function toolEnv() {
  const extra = [join(homedir(), ".cargo", "bin")];
  if (process.platform === "win32" && process.env.ProgramFiles) {
    extra.push(join(process.env.ProgramFiles, "nodejs"));
  }
  return { ...process.env, PATH: [...extra, process.env.PATH ?? process.env.Path ?? ""].join(delimiter) };
}
